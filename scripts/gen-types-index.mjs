// Regenerates packages/types/src/index.ts from the files ts-rs wrote into src/generated.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "packages", "types", "src");
const names = readdirSync(join(root, "generated"))
  .filter((f) => f.endsWith(".ts"))
  .map((f) => f.slice(0, -3))
  .sort();
const body = names.map((n) => `export type { ${n} } from "./generated/${n}";`).join("\n");
writeFileSync(join(root, "index.ts"), `// Generated by scripts/gen-types-index.mjs — do not edit.\n${body}\n`);
console.log(`wrote ${names.length} type exports`);
